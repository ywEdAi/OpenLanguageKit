#!/usr/bin/env python3
"""Validate blueprint/profiles.json and blueprint/science-links.json, then bundle blueprint/science.js.

    python3 blueprint/build.py

science.js is `window.KT_SCIENCE = {...}` (families, planning rules, and the label / evidenceStatus / first
limitation of every referenced pedagogy node) plus `window.KT_TRACK_PROFILES`. pedagogy/ is read, never written.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def main():
    errors = []
    ped = {n['id']: n for n in json.loads((ROOT / 'pedagogy/graph.json').read_text())['nodes']}
    families = json.loads((ROOT / 'curriculum/primitives/primitives.json').read_text())['families']
    links = json.loads((HERE / 'science-links.json').read_text())
    profiles = json.loads((HERE / 'profiles.json').read_text())['tracks']

    used = set()
    for fam, items in links['families'].items():
        if fam not in families:
            errors.append(f'science-links: unknown family {fam}')
        for it in items:
            used.add(it['ped'])
    for fam in families:
        if fam not in links['families']:
            errors.append(f'science-links: family {fam} has no reference')
    for it in links['planning']:
        used.add(it['ped'])
    for pid in sorted(used):
        if pid not in ped:
            errors.append(f'science-links: {pid} is not in pedagogy/graph.json')

    track_ids = set()
    for path in sorted((ROOT / 'curriculum').glob('*/tracks.json')):
        data = json.loads(path.read_text())
        for t in (data['tracks'] if isinstance(data, dict) else data):
            track_ids.add(t['id'])
    for tid in sorted(track_ids - set(profiles)):
        errors.append(f'profiles: track {tid} has no profile')
    for tid in sorted(set(profiles) - track_ids):
        errors.append(f'profiles: {tid} is not a track')
    for tid, p in profiles.items():
        if not set(p['ages']) <= {'5-7', '8-12', '13-17', 'adult'} or p['start'] not in ('zero', 'some'):
            errors.append(f'profiles: {tid} has an unknown age band or start')

    if errors:
        raise SystemExit('\n'.join(errors))

    nodes = {pid: {'label': ped[pid]['label'], 'kind': ped[pid]['kind'], 'evidenceStatus': ped[pid].get('evidenceStatus'),
                   'limitation': (ped[pid].get('limitations') or [None])[0]} for pid in sorted(used)}
    science = {'basis': links['basis'], 'families': links['families'], 'planning': links['planning'], 'nodes': nodes}
    (HERE / 'science.js').write_text(
        '/* generated by blueprint/build.py — do not edit */\nwindow.KT_SCIENCE = ' + json.dumps(science, ensure_ascii=False) +
        ';\nwindow.KT_TRACK_PROFILES = ' + json.dumps(profiles, ensure_ascii=False) + ';\n')
    print(f'blueprint: {len(nodes)} learning-science nodes linked, {len(profiles)} track profiles; 0 errors')


if __name__ == '__main__':
    main()
